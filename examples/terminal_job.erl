% Finish only after the terminal parser acknowledges all preceding output.
-module(terminal_job).
-export([main/1]).

% The reply is a local round trip through tmux. The deadline starts after
% raw mode is on and the request is written, so VM and script start-up do
% not count against it. It is long enough for a loaded host and short
% enough that a missing reply fails quickly.
-define(REPLY_MS, 2000).

main(_) ->
    case shell:start_interactive({noshell, raw}) of
        ok -> run();
        {error, Reason} -> fail(io_lib:format("no terminal: ~p", [Reason]))
    end.

run() ->
    % The reply is generated by tmux after parsing the preceding output.
    io:put_chars(<<"build complete\r\n\e[5n">>),
    Self = self(),
    spawn(fun() -> Self ! {reply, io:get_chars('', 4)} end),
    receive
        {reply, "\e[0n"} -> halt(0);
        {reply, eof} -> fail("terminal closed before acknowledging output");
        {reply, _} -> fail("unexpected terminal acknowledgement")
    after ?REPLY_MS -> fail("terminal did not acknowledge output")
    end.

fail(Message) ->
    io:put_chars(standard_error, [Message, "\r\n"]),
    halt(1).
