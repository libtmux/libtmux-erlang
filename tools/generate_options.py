#!/usr/bin/env python3
"""Generate option metadata and its reference from pinned tmux source tables."""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "schema/options.json"
MODULE = ROOT / "apps/libtmux_erlang/src/tmux_option_data.erl"
REFERENCE = ROOT / "docs/options-reference.md"
STRING = r'"(?:[^"\\]|\\.)*"'


def initializers(text: str):
    """Read whole C initializers, ignoring braces inside escaped literals."""
    text = text.split("options_table[] = {", 1)[1]
    depth = 0
    quote = None
    escaped = False
    start = 0
    for offset, char in enumerate(text):
        if quote:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                quote = None
        elif char in ('"', "'"):
            quote = char
        elif char == "{":
            if depth == 0:
                start = offset
            depth += 1
        elif char == "}":
            if depth == 0:
                return
            depth -= 1
            if depth == 0:
                yield text[start:offset + 1]
    raise ValueError("unterminated options_table")


def refresh(tree: Path) -> dict:
    pins = json.loads((ROOT / "tools/ci/tmux-sources.json").read_text())["versions"]
    sources = {}
    entries = {}
    for version, pin in pins.items():
        source = subprocess.check_output(
            ["git", "-C", str(tree), "show", f"{pin['commit']}:options-table.c"])
        # Expand hook macros, including concatenated names, without tmux headers.
        text = re.sub(rb"^\s*#include[^\n]*", b"", source, flags=re.M)
        if re.search(rb"^\s*#\s*(?:if|elif|else|endif)\b", text, flags=re.M):
            raise ValueError("conditional table requires an explicit extraction policy")
        expanded = subprocess.check_output(["cc", "-E", "-P", "-x", "c", "-"], input=text)
        seen = set()
        for row in initializers(expanded.decode()):
            if re.search(r"\.name\s*=\s*NULL", row):
                continue
            name_match = re.search(r'\.name\s*=\s*((?:' + STRING + r'\s*)+),', row)
            if name_match is None:
                raise ValueError(f"unrecognized option name: {row[:80]}")
            name = "".join(ast.literal_eval(s) for s in re.findall(STRING, name_match[1]))
            if not re.fullmatch(r"[a-z][a-z0-9-]*", name) or name in seen:
                raise ValueError(f"invalid or duplicate option: {name}")
            seen.add(name)
            scope = re.search(r"\.scope\s*=\s*([^,]+),", row)[1]
            scopes = re.findall(r"OPTIONS_TABLE_(SERVER|SESSION|WINDOW|PANE)", scope)
            if not scopes or re.sub(r"OPTIONS_TABLE_(SERVER|SESSION|WINDOW|PANE)|[\s|]", "", scope):
                raise ValueError(f"unrecognized scope: {scope}")
            kind = re.search(r"\.type\s*=\s*OPTIONS_TABLE_(\w+)", row)[1].lower()
            if kind not in ("choice", "colour", "command", "flag", "key", "number", "string"):
                raise ValueError(f"unrecognized option type: {kind}")
            metadata = {"scopes": [s.lower() for s in scopes], "type": kind,
                        "array": "OPTIONS_TABLE_IS_ARRAY" in row,
                        "hook": "OPTIONS_TABLE_IS_HOOK" in row}
            variants = entries.setdefault(name, [])
            for variant in variants:
                if variant["metadata"] == metadata:
                    variant["versions"].append(version)
                    break
            else:
                variants.append({"versions": [version], "metadata": metadata})
        sources[version] = {"commit": pin["commit"], "file": "options-table.c",
                            "sha256": hashlib.sha256(source).hexdigest(),
                            "entries": len(seen)}
    return {"version": 1, "sources": sources, "entries": dict(sorted(entries.items()))}


def binary(value: str) -> str:
    return f'<<"{value}">>'


def metadata(value: dict) -> str:
    scopes = ", ".join(value["scopes"])
    return (f'#{{scopes => [{scopes}], type => {value["type"]}, '
            f'array => {str(value["array"]).lower()}, hook => {str(value["hook"]).lower()}}}')


def generated(data: dict) -> dict[Path, str]:
    versions = list(data["sources"])
    erlang = ["%% Generated by tools/generate_options.py; do not edit.\n",
              "-module(tmux_option_data).\n-moduledoc false.\n",
              "-export([versions/0, names/0, variants/1]).\n\n",
              "-spec versions() -> [binary()].\nversions() -> [",
              ", ".join(map(binary, versions)), "].\n\n",
              "-spec names() -> [binary()].\nnames() -> [\n    ",
              ",\n    ".join(map(binary, data["entries"])), "].\n\n",
              "-spec variants(binary()) -> [{[binary()], map()}].\n"]
    for name, variants in data["entries"].items():
        erlang.append(f"variants({binary(name)}) -> [\n")
        erlang.append(",\n".join("    {[" + ", ".join(map(binary, item["versions"])) +
                                 "], " + metadata(item["metadata"]) + "}"
                                 for item in variants))
        erlang.append("];\n")
    erlang.append("variants(_) -> [].\n")
    docs = ["# Option catalogue\n\n",
            "Generated from pinned tmux `options-table.c` files by\n",
            "`tools/generate_options.py`. [Scoped options](options.md) defines the\n",
            "public API. Types describe tmux's parser; values use binary text.\n",
            "Hooks appear for discovery and are rejected by the option API.\n\n",
            "## Sources\n\n| Version | Source | SHA-256 | Entries |\n",
            "| --- | --- | --- | --- |\n"]
    for version, source in data["sources"].items():
        url = f'https://github.com/tmux/tmux/blob/{source["commit"]}/options-table.c'
        docs.append(f'| {version} | [Table]({url}) | `{source["sha256"]}` | {source["entries"]} |\n')
    docs.extend(["\n## Options and hooks\n\n",
                 "| Name | Versions | Scopes | Type | Array | Hook |\n",
                 "| --- | --- | --- | --- | --- | --- |\n"])
    for name, variants in data["entries"].items():
        for variant in variants:
            meta = variant["metadata"]
            docs.append(f'| `{name}` | {", ".join(variant["versions"])} | '
                        f'{", ".join(meta["scopes"])} | {meta["type"]} | '
                        f'{str(meta["array"]).lower()} | {str(meta["hook"]).lower()} |\n')
    return {MODULE: "".join(erlang), REFERENCE: "".join(docs)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh-from", type=Path, help="local tmux Git tree; needs C preprocessor")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.refresh_from and args.check:
        parser.error("refresh and check are separate operations")
    if args.refresh_from:
        SCHEMA.write_text(json.dumps(refresh(args.refresh_from), indent=2) + "\n")
    data = json.loads(SCHEMA.read_text())
    pins = json.loads((ROOT / "tools/ci/tmux-sources.json").read_text())["versions"]
    if {v: s["commit"] for v, s in data["sources"].items()} != {v: p["commit"] for v, p in pins.items()}:
        raise ValueError("option catalogue source pins differ from CI pins")
    for path, content in generated(data).items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"Generated option catalogue drift: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)
    print("PASS: generated option catalogue and source reference")


if __name__ == "__main__":
    main()
